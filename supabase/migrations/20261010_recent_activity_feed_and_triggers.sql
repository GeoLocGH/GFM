-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. ENSURE CORE INTERACTION TABLES EXIST
-- 2a. Marketplace Orders Table
CREATE TABLE IF NOT EXISTS public.orders (
    id TEXT PRIMARY KEY,
    buyer_id TEXT,
    buyer_name TEXT,
    seller_id TEXT,
    item_name TEXT,
    items JSONB DEFAULT '[]'::jsonb,
    quantity INTEGER DEFAULT 1,
    total NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    status TEXT NOT NULL DEFAULT 'Processing' CHECK (status IN ('Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled')),
    payment_status TEXT DEFAULT 'escrowed',
    handover_code TEXT,
    region TEXT DEFAULT 'All Regions',
    date TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2b. Equipment Rental Listings Table
CREATE TABLE IF NOT EXISTS public.equipment (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'Tractor',
    owner TEXT NOT NULL,
    owner_id TEXT,
    owner_email TEXT,
    owner_phone TEXT,
    location TEXT NOT NULL,
    price_per_day NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    image_url TEXT,
    available BOOLEAN DEFAULT true,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2c. Equipment Rental & Marketplace Inquiries Table
CREATE TABLE IF NOT EXISTS public.inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    item_id TEXT,
    item_type TEXT NOT NULL DEFAULT 'equipment' CHECK (item_type IN ('marketplace', 'equipment')),
    name TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    message TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'reviewed', 'resolved')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2d. Community Forum Posts & Replies Table
CREATE TABLE IF NOT EXISTS public.forum_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author TEXT NOT NULL,
    author_id TEXT,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    image_url TEXT,
    images JSONB DEFAULT '[]'::jsonb,
    replies JSONB DEFAULT '[]'::jsonb,
    region TEXT DEFAULT 'All Regions',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2e. User Activity Logs Table
CREATE TABLE IF NOT EXISTS public.user_activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT,
    user_name TEXT,
    user_email TEXT,
    user_type TEXT DEFAULT 'farmer' CHECK (user_type IN ('farmer', 'buyer', 'seller', 'admin', 'system')),
    action TEXT NOT NULL,
    details TEXT NOT NULL,
    region TEXT NOT NULL DEFAULT 'All Regions',
    ip_address TEXT,
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. PERFORMANCE INDEXES FOR DASHBOARD FEED
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_orders_buyer_seller ON public.orders (buyer_id, seller_id);
CREATE INDEX IF NOT EXISTS idx_inquiries_item_type_created ON public.inquiries (item_type, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_inquiries_user_id ON public.inquiries (user_id);
CREATE INDEX IF NOT EXISTS idx_forum_posts_created_at ON public.forum_posts (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_user_activity_logs_created_at ON public.user_activity_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_user_activity_logs_user_id ON public.user_activity_logs (user_id);

-- 4. ROW LEVEL SECURITY (RLS) POLICIES
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipment ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.forum_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_activity_logs ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'orders' AND policyname = 'Public read orders') THEN
        CREATE POLICY "Public read orders" ON public.orders FOR SELECT TO anon, authenticated USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'orders' AND policyname = 'Public insert orders') THEN
        CREATE POLICY "Public insert orders" ON public.orders FOR INSERT TO anon, authenticated WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'orders' AND policyname = 'Public update orders') THEN
        CREATE POLICY "Public update orders" ON public.orders FOR UPDATE TO anon, authenticated USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'inquiries' AND policyname = 'Public read inquiries') THEN
        CREATE POLICY "Public read inquiries" ON public.inquiries FOR SELECT TO anon, authenticated USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'inquiries' AND policyname = 'Public insert inquiries') THEN
        CREATE POLICY "Public insert inquiries" ON public.inquiries FOR INSERT TO anon, authenticated WITH CHECK (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'forum_posts' AND policyname = 'Public read forum_posts') THEN
        CREATE POLICY "Public read forum_posts" ON public.forum_posts FOR SELECT TO anon, authenticated USING (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'forum_posts' AND policyname = 'Public insert forum_posts') THEN
        CREATE POLICY "Public insert forum_posts" ON public.forum_posts FOR INSERT TO anon, authenticated WITH CHECK (true);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'forum_posts' AND policyname = 'Public update forum_posts') THEN
        CREATE POLICY "Public update forum_posts" ON public.forum_posts FOR UPDATE TO anon, authenticated USING (true);
    END IF;
END $$;

-- 5. UNIFIED RECENT ACTIVITY VIEW (COMBINES RENTALS, ORDERS, FORUM REPLIES & AUDIT LOGS)
CREATE OR REPLACE VIEW public.v_recent_activity_feed AS
-- 5a. Market Orders
SELECT
    'order-' || o.id::text AS activity_id,
    'order'::text AS category,
    COALESCE(o.item_name, (o.items->>0), 'Agricultural Marketplace Order') AS title,
    'Market order ' || o.id::text || ' · ' || COALESCE(o.status, 'Processing') AS description,
    o.created_at AS timestamp,
    COALESCE(o.status, 'Processing') AS status_label,
    CASE
        WHEN o.status IN ('Delivered', 'Shipped') THEN 'nominal'
        ELSE 'warning'
    END AS status_tone,
    o.total AS amount_ghs,
    o.id::text AS reference_code,
    COALESCE(o.region, 'Ghana Market') AS region,
    COALESCE(o.buyer_name, 'Agro Buyer') AS actor_name,
    o.buyer_id AS user_id,
    'ORDERS'::text AS target_view
FROM public.orders o

UNION ALL

-- 5b. Equipment Rental Inquiries
SELECT
    'rental-inq-' || i.id::text AS activity_id,
    'rental'::text AS category,
    'Equipment Rental Request'::text AS title,
    COALESCE(i.message, 'Submitted equipment rental availability inquiry.') AS description,
    i.created_at AS timestamp,
    CASE WHEN i.status = 'resolved' THEN 'Confirmed' ELSE 'Inquiry Sent' END AS status_label,
    CASE WHEN i.status = 'resolved' THEN 'nominal' ELSE 'warning' END AS status_tone,
    NULL::numeric AS amount_ghs,
    'RNT-' || i.id::text AS reference_code,
    'All Regions'::text AS region,
    COALESCE(i.name, 'Farmer') AS actor_name,
    i.user_id AS user_id,
    'RENTAL'::text AS target_view
FROM public.inquiries i
WHERE i.item_type = 'equipment'

UNION ALL

-- 5c. Community Forum Replies (Unnested from JSONB replies array)
SELECT
    'forum-reply-' || fp.id::text || '-' || COALESCE(r.value->>'id', '0') AS activity_id,
    'forum'::text AS category,
    'Replied to "' || fp.title || '"' AS title,
    COALESCE(r.value->>'content', 'Posted a reply in the community forum.') AS description,
    COALESCE((r.value->>'created_at')::timestamptz, fp.created_at) AS timestamp,
    'Forum Reply'::text AS status_label,
    'nominal'::text AS status_tone,
    NULL::numeric AS amount_ghs,
    'FRM-' || fp.id::text AS reference_code,
    COALESCE(fp.region, 'All Regions') AS region,
    COALESCE(r.value->>'author', 'Community Farmer') AS actor_name,
    fp.author_id AS user_id,
    'FORUM'::text AS target_view
FROM public.forum_posts fp
CROSS JOIN LATERAL jsonb_array_elements(
    CASE WHEN jsonb_typeof(fp.replies) = 'array' THEN fp.replies ELSE '[]'::jsonb END
) AS r(value)

UNION ALL

-- 5d. Community Forum Discussion Threads
SELECT
    'forum-post-' || fp.id::text AS activity_id,
    'forum'::text AS category,
    'Discussion: "' || fp.title || '"' AS title,
    LEFT(fp.content, 140) AS description,
    fp.created_at AS timestamp,
    jsonb_array_length(CASE WHEN jsonb_typeof(fp.replies) = 'array' THEN fp.replies ELSE '[]'::jsonb END)::text || ' Replies' AS status_label,
    'neutral'::text AS status_tone,
    NULL::numeric AS amount_ghs,
    'FRM-' || fp.id::text AS reference_code,
    COALESCE(fp.region, 'All Regions') AS region,
    fp.author AS actor_name,
    fp.author_id AS user_id,
    'FORUM'::text AS target_view
FROM public.forum_posts fp;

-- 6. RPC FUNCTION: FETCH & FILTER USER RECENT ACTIVITY
CREATE OR REPLACE FUNCTION public.get_user_recent_activity(
    p_user_id TEXT DEFAULT NULL,
    p_user_name TEXT DEFAULT NULL,
    p_category TEXT DEFAULT 'all',
    p_search TEXT DEFAULT NULL,
    p_limit INTEGER DEFAULT 15
)
RETURNS TABLE (
    activity_id TEXT,
    category TEXT,
    title TEXT,
    description TEXT,
    "timestamp" TIMESTAMP WITH TIME ZONE,
    status_label TEXT,
    status_tone TEXT,
    amount_ghs NUMERIC,
    reference_code TEXT,
    region TEXT,
    actor_name TEXT,
    is_current_user BOOLEAN,
    target_view TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RETURN QUERY
    SELECT
        v.activity_id,
        v.category,
        v.title,
        v.description,
        v.timestamp,
        v.status_label,
        v.status_tone,
        v.amount_ghs,
        v.reference_code,
        v.region,
        v.actor_name,
        (
            (p_user_id IS NOT NULL AND v.user_id = p_user_id)
            OR (p_user_name IS NOT NULL AND LOWER(v.actor_name) = LOWER(p_user_name))
        ) AS is_current_user,
        v.target_view
    FROM public.v_recent_activity_feed v
    WHERE
        (p_category = 'all' OR v.category = p_category)
        AND (
            p_search IS NULL
            OR p_search = ''
            OR v.title ILIKE '%' || p_search || '%'
            OR v.description ILIKE '%' || p_search || '%'
            OR v.reference_code ILIKE '%' || p_search || '%'
            OR v.region ILIKE '%' || p_search || '%'
        )
    ORDER BY v.timestamp DESC
    LIMIT p_limit;
END;
$$;

-- 7. AUTOMATED TRIGGERS TO SYNC INTERACTIONS INTO USER_ACTIVITY_LOGS
-- 7a. Trigger when a new Order is inserted or updated
CREATE OR REPLACE FUNCTION public.fn_trg_log_order_activity()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    INSERT INTO public.user_activity_logs (
        user_id, user_name, user_type, action, details, region, metadata, created_at
    ) VALUES (
        NEW.buyer_id,
        COALESCE(NEW.buyer_name, 'Agro Buyer'),
        'buyer',
        CASE WHEN TG_OP = 'INSERT' THEN 'ORDER_PLACED' ELSE 'ORDER_STATUS_UPDATED' END,
        'Order ' || NEW.id || ' (' || COALESCE(NEW.item_name, 'Market Produce') || ') — Status: ' || COALESCE(NEW.status, 'Processing'),
        COALESCE(NEW.region, 'All Regions'),
        jsonb_build_object('order_id', NEW.id, 'total_ghs', NEW.total, 'status', NEW.status),
        timezone('utc'::text, now())
    );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_log_order_activity ON public.orders;
CREATE TRIGGER trg_log_order_activity
AFTER INSERT OR UPDATE OF status ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.fn_trg_log_order_activity();

-- 7b. Trigger when an Equipment Rental Inquiry is submitted
CREATE OR REPLACE FUNCTION public.fn_trg_log_rental_inquiry()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    IF NEW.item_type = 'equipment' THEN
        INSERT INTO public.user_activity_logs (
            user_id, user_name, user_email, user_type, action, details, region, metadata, created_at
        ) VALUES (
            NEW.user_id,
            NEW.name,
            NEW.email,
            'farmer',
            'EQUIPMENT_RENTAL_INQUIRY',
            LEFT(NEW.message, 160),
            'All Regions',
            jsonb_build_object('inquiry_id', NEW.id, 'item_id', NEW.item_id, 'status', NEW.status),
            timezone('utc'::text, now())
        );
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_log_rental_inquiry ON public.inquiries;
CREATE TRIGGER trg_log_rental_inquiry
AFTER INSERT ON public.inquiries
FOR EACH ROW EXECUTE FUNCTION public.fn_trg_log_rental_inquiry();

